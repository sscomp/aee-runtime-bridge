#!/usr/bin/env python3
"""Canonical AEE MCP gateway installer (os-native / restricted profiles).

Idempotent, preflighted, receipt-producing, rollback-capable installation of
the AEE MCP gateway for one of the two first-class deployment profiles
(`config/profiles/profile-schema-v1`).

Design boundaries (work order AEE_V2_PHASE3_* / Phase 1-2 design):
- user-scope actions only: never acquires privileges (no sudo/setuid). The
  restricted profile's system units are STAGED plus printed as operator
  commands, never installed by this tool.
- secret VALUES are never generated, printed, archived or copied: the
  operator's env file (0600) is validated by name schema only.
- idempotent: re-running with unchanged inputs changes nothing and never
  restarts or reloads.
- rollback: every apply takes timestamped backups; `--rollback-last` restores
  the previous receipt's backups; `--uninstall` removes what was installed.
- SSH is never used or required by this installer.

Exit codes: 0 ok, 1 preflight/validation failure (nothing written), 2 apply
failure (backups preserved).
"""
import argparse
import hashlib
import json
import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.validate_profiles import (  # noqa: E402
    load_schema, validate_env_path, validate_examples, parse_env)

RECEIPT_SCHEMA = 'aee-gateway-installer-receipt-v1'
NOCHANGE = 'nochange'


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as handle:
        for chunk in iter(lambda: handle.read(65536), b''):
            digest.update(chunk)
    return digest.hexdigest()


# ---------------------------------------------------------------------------
# Preflight
# ---------------------------------------------------------------------------

def preflight(args, *, identity_report=None):
    """Return (errors, warnings, facts). Never writes. Fail before any change."""
    errors, warnings, facts = [], [], []
    profile = args.profile

    if not sys.platform.startswith('linux'):
        errors.append(f'unsupported platform {sys.platform!r}; AEE gateway targets Linux')
    facts.append(f'platform={sys.platform}')
    facts.append(f'arch={os.uname().machine}')
    facts.append(f'uid={os.getuid()} user={os.environ.get("USER", "?")}')
    facts.append(f'host={socket.gethostname()}')

    # Schema contract itself must be internally consistent.
    schema_errors = validate_examples()
    if schema_errors:
        errors.append(f'profile schema contract invalid: {schema_errors}')

    # Release tree sanity.
    release = Path(args.release_dir).resolve()
    gateway = release / 'mcp_gateway.py'
    if not gateway.is_file():
        errors.append(f'release tree invalid: {gateway} missing '
                      '(build an immutable release per docs/deployment.md §3 or pass --release-dir)')
    else:
        facts.append(f'release_dir={release}')
        facts.append(f'gateway_script_sha256={_sha256(gateway)}')
    py_bin = Path(args.python or (release / '.venv' / 'bin' / 'python'))
    if not py_bin.is_file():
        errors.append(f'interpreter missing: {py_bin} (release build should contain .venv/bin/python)')
    else:
        facts.append(f'python={py_bin}')

    # Env file: schema-conformant (var names/shape only; values not recorded).
    env_path = Path(args.env_path).expanduser().resolve()
    if not env_path.is_file():
        errors.append(
            f'env file missing: {env_path}. Start from '
            f'config/profiles/{profile}.env.example, replace placeholders with '
            'host-owned values, chmod 0600, then re-run. Secret VALUES are never '
            'generated by this installer.')
    else:
        env_findings = validate_env_path(env_path, profile)
        if env_findings:
            errors.extend(env_findings)
        mode = env_path.stat().st_mode & 0o777
        if mode != 0o600:
            errors.append(f'env file mode is {oct(mode)}; must be 0600 (operator-owned secrets)')
        facts.append(f'env_path={env_path}')
        facts.append('env_keys=' + ','.join(sorted(parse_env(env_path.read_text()))))

    # Port availability: bind probe, never reads credential material.
    probe = socket.socket()
    try:
        probe.bind(('127.0.0.1', args.port))
        probe.close()
        facts.append(f'port={args.port} free=true')
    except OSError as exc:
        probe.close()
        errors.append(f'port {args.port} unavailable ({exc.errno}: {os.strerror(exc.errno)})')
        facts.append(f'port={args.port} free=false')

    # Disk headroom.
    root_free = shutil.disk_usage(Path.home()).free
    facts.append(f'home_free_bytes={root_free}')
    if root_free < 512 * 1024 * 1024:
        errors.append('less than 512MB free under the installation root')

    # systemd reachability (user scope) — read-only probe.
    if profile == 'os-native':
        default_units = '~/.config/systemd/user'
        units_dir = Path(args.user_unit_dir or default_units).expanduser()
        if not units_dir.is_dir():
            warnings.append(f'systemd user unit dir {units_dir} does not exist yet (created on apply)')
        if args.systemd_bin and shutil.which(args.systemd_bin) is None:
            warnings.append(f'systemctl not found at {args.systemd_bin}; '
                            'unit will be written but enable/daemon-reload steps will be reported pending')
        linger = Path('/var/lib/systemd/linger') / os.environ.get('USER', Path.home().name)
        facts.append(f'user_lingering={"enabled" if linger.exists() else "disabled"}')
        if not linger.exists():
            warnings.append(
                'user lingering is NOT enabled: the user gateway unit will not survive '
                'logout or cold boot. Enable ONLY by explicit operator choice: '
                '`loginctl enable-linger <user>` (this installer never does it).')

    # Restricted profile: staging-only, no privilege acquisition.
    if profile == 'restricted':
        if not args.staging_dir:
            errors.append('restricted profile requires --staging-dir for staged artifacts')
        if args.apply and args.unit_mode_user:
            errors.append('restricted profile installs system units; the installer only '
                          'stages artifacts and prints operator commands')
        facts.append('restricted_system_units=staged-only')

    # Adapter discovery report (non-fatal; surfaced in receipt + aee_agents).
    adapter_facts, adapter_warnings = _adapter_discovery_report()
    facts.extend(adapter_facts)
    warnings.extend(adapter_warnings)

    # Trusted dispatch presence (os-native): report, never enforce.
    policy = os.getenv('AEE_TRUSTED_DISPATCH_POLICY')
    if policy:
        p = Path(policy)
        facts.append(f'trusted_dispatch_policy={p} exists={p.is_file()}')
        if not p.is_file():
            warnings.append('AEE_TRUSTED_DISPATCH_POLICY points at a missing file: '
                            'write/autonomous admission will fail closed at runtime '
                            '(TrustedDispatch.configured() refuses invalid/empty policy)')
    else:
        warnings.append('AEE_TRUSTED_DISPATCH_POLICY not set in this environment: '
                        'without the trusted policy, write/autonomous stay subject to '
                        'legacy per-job fail-closed gates (never silently enabled)')

    # Install collision: distinguish this installer's own units (sidecar
    # receipt marker) from unmanaged pre-existing units.
    unit_path = _unit_path(args)
    sidecar = Path(str(unit_path) + '.aee-installer.json')
    if unit_path.exists() and not sidecar.exists() and not args.upgrade_authorized:
        errors.append(f'existing unmanaged installation found: {unit_path}; this installer is '
                      'idempotent for its own units but an unmanaged unit is present — '
                      'pass --upgrade-authorized after review, or --check to inspect')
    elif unit_path.exists() and sidecar.exists():
        warnings.append(f'existing own installation {unit_path}; idempotent re-run '
                        '(byte-identical unit produces no change; changes take a backup)')
    elif unit_path.exists():
        warnings.append(f'upgrading over existing unit {unit_path} (pre-change backup taken)')
    return errors, warnings, facts


def _adapter_discovery_report():
    facts, warnings = [], []
    try:
        from aee.mcp_runtime.job_adapters import adapter_specs, resolve_adapter, JobError
    except Exception as exc:  # pragma: no cover - defensive
        return [f'adapter_registry_unavailable={type(exc).__name__}'], \
               ['adapter discovery report unavailable in this environment']
    from aee.mcp_runtime.job_adapters import AGENT_NAMES
    for agent in sorted(AGENT_NAMES):
        try:
            _spec, executable = resolve_adapter(agent)
            facts.append(f'adapter[{agent}]=resolved:{executable}')
        except JobError as exc:
            code = getattr(exc, 'code', None) or getattr(exc, 'error_code', 'unknown')
            facts.append(f'adapter[{agent}]=not_resolved:{code}')
            warnings.append(str(exc))
    return facts, warnings


def _unit_path(args):
    if args.profile == 'os-native':
        unit_name = args.user_unit_name or 'aee-gateway.service'
        return Path(args.user_unit_dir or
                    '~/.config/systemd/user').expanduser().resolve() / unit_name
    staging = Path(args.staging_dir).expanduser().resolve() if args.staging_dir \
        else Path('/tmp/aee-restricted-staging')
    return staging / 'etc-systemd-system-aee-p2c-gateway@.service'


